def row_bits(row, width):
    v = 0
    for i, ch in enumerate(row[:width]):
        if ch == "#":
            v |= 1 << (width - 1 - i)
    return v


def main():
    out = []
    w = out.append
    w("/* port/3ds/gdx3ds_bui_glyphs.h -- GENERATED by tools/bui/gen_bui_glyphs.py. Do not hand-edit.")
    w(" * The bottom-screen UI kit's own pixels (gdx3ds_bui_kit.c): Font2-style extra glyphs (7 rows")
    w(" * of 8 bits, MSB = leftmost column) keyed by Unicode code point, and 16x16 1-bit icons (MSB =")
    w(" * leftmost column). */")
    w("#ifndef GDX3DS_BUI_GLYPHS_H")
    w("#define GDX3DS_BUI_GLYPHS_H")
    w("")
    w("#include <stdint.h>")
    w("")
    w("#define BUI_EXTRA_ROWS 7")
    w("#define BUI_EXTRA_COUNT %d" % len(EXTRA))
    w("static const uint16_t kBuiExtraCodepoint[BUI_EXTRA_COUNT] = {")
    w("    " + ", ".join("0x%04X" % ord(k) for k in EXTRA) + ",")
    w("};")
    w("static const uint8_t kBuiExtraRows[BUI_EXTRA_COUNT][BUI_EXTRA_ROWS] = {")
    for k, rows in EXTRA.items():
        assert len(rows) == 7, k
        w("    {%s}, /* U+%04X */" % (", ".join("0x%02X" % row_bits(r, 8) for r in rows), ord(k)))
    w("};")
    w("")
    w("enum BuiIcon {")
    w("    BUI_ICON_NONE = 0,")
    for k in ICON:
        w("    BUI_ICON_%s," % k.upper())
    w("    BUI_ICON_COUNT")
    w("};")
    w("static const uint16_t kBuiIconRows[BUI_ICON_COUNT][16] = {")
    w("    {0}, /* none */")
    for k, rows in ICON.items():
        assert len(rows) == 16, k
        w("    {%s}, /* %s */" % (", ".join("0x%04X" % row_bits(r, 16) for r in rows), k))
    w("};")
    w("")
    w("#endif /* GDX3DS_BUI_GLYPHS_H */")
    print("\n".join(out))


if __name__ == "__main__":
    main()
